// Command gen writes internal/ops/ops_gen.go from spec/openapi.json: one entry per operation of the API, the one table
// the CLI's commands and the MCP server's tools are both built from (docs/api/design/15-cli-mcp.md section 1).
//
//	go run ./tools/gen            (go generate ./...)
//
// Each operation's arguments are flattened into one JSON Schema object: its path parameters, its query parameters and
// the top-level fields of its body (components inlined), plus idempotency_key where the API requires one. Two
// arguments with the same name are refused: the build fails rather than guess.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type spec struct {
	Info struct {
		Version string `json:"version"`
	} `json:"info"`
	Paths      map[string]map[string]json.RawMessage `json:"paths"`
	Components struct {
		Schemas map[string]map[string]any `json:"schemas"`
	} `json:"components"`
}

type operation struct {
	OperationID string           `json:"operationId"`
	Summary     string           `json:"summary"`
	Description string           `json:"description"`
	Scope       string           `json:"x-pp-scope"`
	Resource    string           `json:"x-pp-resource"`
	Method      string           `json:"x-pp-method"`
	Idempotent  bool             `json:"x-pp-idempotent"`
	RetrySafe   bool             `json:"x-pp-retry-safe"`
	Envs        []string         `json:"x-pp-environments"`
	Pagination  *json.RawMessage `json:"x-pp-pagination"`
	Parameters  []struct {
		Name        string         `json:"name"`
		In          string         `json:"in"`
		Description string         `json:"description"`
		Required    bool           `json:"required"`
		Schema      map[string]any `json:"schema"`
	} `json:"parameters"`
	RequestBody *struct {
		Content map[string]struct {
			Schema map[string]any `json:"schema"`
		} `json:"content"`
	} `json:"requestBody"`
	Responses map[string]struct {
		Content map[string]struct {
			Schema map[string]any `json:"schema"`
		} `json:"content"`
	} `json:"responses"`
}

var kebabRe = regexp.MustCompile(`([a-z0-9])([A-Z])`)

func kebab(s string) string { return strings.ToLower(kebabRe.ReplaceAllString(s, "$1-$2")) }

// inline replaces every $ref with its component, drops what a tool's caller does not need (examples, x-pp-*)
func inline(v any, comps map[string]map[string]any, depth int) any {
	if depth > 12 {
		return map[string]any{"type": "object"}
	}
	switch x := v.(type) {
	case map[string]any:
		if ref, ok := x["$ref"].(string); ok {
			name := ref[strings.LastIndex(ref, "/")+1:]
			return inline(map[string]any(comps[name]), comps, depth+1)
		}
		out := map[string]any{}
		for k, val := range x {
			if k == "example" || strings.HasPrefix(k, "x-") {
				continue
			}
			out[k] = inline(val, comps, depth+1)
		}
		return out
	case []any:
		out := make([]any, len(x))
		for i, val := range x {
			out[i] = inline(val, comps, depth+1)
		}
		return out
	default:
		return v
	}
}

// moduleRoot is the folder of go.mod: go generate runs this in internal/ops, a person anywhere in the module.
func moduleRoot() string {
	dir, err := os.Getwd()
	must(err)
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			must(fmt.Errorf("no go.mod above %s", dir))
		}
		dir = parent
	}
}

func main() {
	root := moduleRoot()
	raw, err := os.ReadFile(filepath.Join(root, "spec", "openapi.json"))
	must(err)
	var s spec
	must(json.Unmarshal(raw, &s))
	type entry struct {
		path, http string
		op         operation
	}
	var entries []entry
	for path, item := range s.Paths {
		for http, rawOp := range item {
			var o operation
			must(json.Unmarshal(rawOp, &o))
			entries = append(entries, entry{path, strings.ToUpper(http), o})
		}
	}
	sort.Slice(entries, func(i, j int) bool {
		return entries[i].op.OperationID < entries[j].op.OperationID
	})

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/gen from spec/openapi.json. DO NOT EDIT: run `go generate ./...`.\n\npackage ops\n\n")
	fmt.Fprintf(&b, "// SpecVersion is the version of the API spec this table was made from.\nconst SpecVersion = %q\n\n", s.Info.Version)
	fmt.Fprintf(&b, "// All is every operation of the API, by operationId.\nvar All = []Op{\n")
	for _, e := range entries {
		o := e.op
		props := map[string]any{}
		var required []string
		var pathParams, query, bodyFields []string
		add := func(name string, schema any, req bool) {
			if _, taken := props[name]; taken {
				fail("%s: two arguments named %q", o.OperationID, name)
			}
			props[name] = schema
			if req {
				required = append(required, name)
			}
		}
		for _, p := range o.Parameters {
			switch p.In {
			case "path":
				sch := inline(p.Schema, s.Components.Schemas, 0).(map[string]any)
				sch["description"] = p.Description
				add(p.Name, sch, true)
				pathParams = append(pathParams, p.Name)
			case "query":
				sch := inline(p.Schema, s.Components.Schemas, 0).(map[string]any)
				sch["description"] = p.Description
				add(p.Name, sch, false)
				query = append(query, p.Name)
			}
		}
		hasBody := o.RequestBody != nil
		if hasBody {
			body := inline(o.RequestBody.Content["application/json"].Schema, s.Components.Schemas, 0).(map[string]any)
			bodyProps, _ := body["properties"].(map[string]any)
			bodyReq := map[string]bool{}
			if rs, ok := body["required"].([]any); ok {
				for _, r := range rs {
					bodyReq[r.(string)] = true
				}
			}
			names := make([]string, 0, len(bodyProps))
			for n := range bodyProps {
				names = append(names, n)
			}
			sort.Strings(names)
			for _, n := range names {
				add(n, bodyProps[n], bodyReq[n])
				bodyFields = append(bodyFields, n)
			}
		}
		if o.Idempotent {
			add("idempotency_key", map[string]any{"type": "string", "minLength": 1, "maxLength": 128, "pattern": "^[\\x21-\\x7e]+$",
				"description": "A value of your own for this action, the same on every try of it: the API never does it twice. After an uncertain outcome, repeat with the same key, never a new one."}, true)
		}
		sort.Strings(required)
		schema := map[string]any{"type": "object", "properties": props, "additionalProperties": false}
		if len(required) > 0 {
			schema["required"] = required
		}
		js, err := json.Marshal(schema)
		must(err)
		list := false
		if ok, found := o.Responses["200"]; found {
			if c, okc := ok.Content["application/json"]; okc {
				if p, okp := c.Schema["properties"].(map[string]any); okp {
					if d, okd := p["data"].(map[string]any); okd && d["type"] == "array" {
						list = true
					}
				}
			}
		}
		fmt.Fprintf(&b, "\t{ID: %q, Name: %q, Resource: %q, Method: %q, HTTP: %q, Path: %q, Summary: %q, Description: %q, Scope: %q, Idempotent: %t, RetrySafe: %t, List: %t, Paged: %t, Envs: %#v, PathParams: %#v, Query: %#v, Body: %t, BodyFields: %#v, InputSchema: %q},\n",
			o.OperationID, kebab(o.OperationID), o.Resource, o.Method, e.http, e.path, o.Summary, o.Description, o.Scope, o.Idempotent, o.RetrySafe || e.http == "GET", list, o.Pagination != nil, o.Envs, pathParams, query, hasBody, bodyFields, string(js))
	}
	fmt.Fprintf(&b, "}\n")
	src, err := format.Source(b.Bytes())
	must(err)
	must(os.WriteFile(filepath.Join(root, "internal", "ops", "ops_gen.go"), src, 0o644))
}

func must(err error) {
	if err != nil {
		fail("%v", err)
	}
}

func fail(f string, a ...any) {
	fmt.Fprintf(os.Stderr, "gen: "+f+"\n", a...)
	os.Exit(1)
}
